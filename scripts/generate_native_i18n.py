"""Validate native messages and generate frozen UI data and API language codes."""
import argparse
import hashlib
import json
from pathlib import Path
import pprint
import re

ROOT=Path(__file__).resolve().parents[1]
BASE=ROOT/'desktop/src/ptb_desktop'


def generate(check=False,review=False):
    locales=json.loads((ROOT/'frontend/src/i18n/languages.json').read_text('utf-8'))
    codes=[row['code'] for row in locales]
    if len(set(codes))!=len(codes) or 'zh-CN' not in codes or any(not isinstance(code,str) or not re.fullmatch(r'[A-Za-z][A-Za-z0-9-]{0,30}',code) for code in codes):raise ValueError('Invalid language registry')
    rows={code:json.loads((BASE/'locales'/f'{code}.json').read_text('utf-8')) for code in codes}
    source=rows['zh-CN']
    params=lambda value:set(re.findall(r'\{([a-zA-Z_][a-zA-Z0-9_]*)\}',value))
    for code,messages in rows.items():
        if set(messages)!=set(source):raise ValueError('Native message keys differ: '+code)
        for key,text in messages.items():
            if not isinstance(text,str) or not text.strip():raise ValueError('Empty native message: '+key)
            if params(text)!=params(source[key]):raise ValueError('Native named parameters differ: '+key)
            # File-dialog patterns are contracts, independent of their captions.
            if re.findall(r'\(\*[^)]*\)',text)!=re.findall(r'\(\*[^)]*\)',source[key]):raise ValueError('Native file filters differ: '+key)
    hashes={code:hashlib.sha256(json.dumps(value,ensure_ascii=False,sort_keys=True).encode()).hexdigest() for code,value in rows.items()}
    review_file=BASE/'locales/reviews.json'
    reviews=json.loads(review_file.read_text('utf-8')) if review_file.is_file() else {}
    entries={key:{code:hashlib.sha256(messages[key].encode()).hexdigest() for code,messages in rows.items()} for key in source}
    if review:
        reviews=entries
        review_file.write_text(json.dumps(reviews,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    pending=[key for key,identities in entries.items() if reviews.get(key)!=identities]
    if check and pending:raise ValueError('Native messages need review: '+', '.join(pending[:20]))
    text='# Generated by scripts/generate_native_i18n.py; do not edit.\n'
    text+='NATIVE_MESSAGES = '+pprint.pformat(rows,width=120,sort_dicts=False)+'\n'
    text+='SOURCE_HASHES = '+repr(hashes)+'\n'
    target=BASE/'native_messages_data.py'
    if check:
        if not target.is_file() or target.read_text('utf-8')!=text:raise ValueError('Native message data is stale')
    else:target.write_text(text,encoding='utf-8')
    api_text='# Generated by scripts/generate_native_i18n.py from the shared language registry; do not edit.\n'
    api_text+='SUPPORTED_UI_LOCALES = '+repr(tuple(codes))+'\n'
    api_target=ROOT/'backend/src/ptb_api/language_codes.py'
    if check:
        if not api_target.is_file() or api_target.read_text('utf-8')!=api_text:raise ValueError('API language codes are stale')
    else:api_target.write_text(api_text,encoding='utf-8')
    return {'locales':codes,'messages':len(source),'source_sha256':hashes,'pending_reviews':len(pending)}


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');parser.add_argument('--review',action='store_true')
    args=parser.parse_args()
    print(json.dumps(generate(args.check,args.review),ensure_ascii=False))
