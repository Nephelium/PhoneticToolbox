"""Generate localized landing pages from one maintained Chinese template.

--inventory lists untranslated source messages. --check checks coverage and
generated bytes without changing files. No translation service is contacted.
"""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import html
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "temporary-site"
TEMPLATE = SITE / "content/home.zh-CN.html"
CJK = re.compile(r"[\u3400-\u9fff]")
NUMBER = re.compile(r"\d+(?:\.\d+)*")
VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source", "track", "wbr"}
ATTRS = {"alt", "title", "aria-label", "placeholder", "content", "data-caption", "data-title", "data-empty-label"}


def canonical(text):
    values = []
    def replace(match):
        values.append(match[0])
        return "{" + str(len(values) - 1) + "}"
    return NUMBER.sub(replace, text), values


def available_languages():
    result = [{"language": "zh-CN", "nativeName": "简体中文", "directory": ""}]
    for path in sorted((SITE / "locales").glob("*.json")):
        data = json.loads(path.read_text("utf-8"))
        language = data["language"]
        if not re.fullmatch(r"[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*", language) or path.stem != language:
            raise ValueError(f"Invalid language catalog filename: {path.name}")
        result.append({"language": language, "nativeName": data.get("nativeName", language), "directory": language})
    return result


class Catalog:
    def __init__(self, language="en"):
        self.language = language
        self.data = json.loads((SITE / "locales" / (language + ".json")).read_text("utf-8"))
        self.messages = self.data["messages"]
        self.fragments = sorted(self.data.get("fragments", {}).items(), key=lambda row: -len(row[0]))
        self.missing, self.used = {}, set()

    def translate(self, text, context):
        if not CJK.search(text):
            return text
        prefix = text[:len(text) - len(text.lstrip())]
        suffix = text[len(text.rstrip()):]
        original = text.strip()
        key, values = canonical(original)
        if key in self.messages and self.messages[key] is not None:
            translated = self.messages[key]
            self.used.add(key)
            source_slots = Counter(re.findall(r"\{\d+\}", key))
            if Counter(re.findall(r"\{\d+\}", translated)) != source_slots:
                raise ValueError(f"Translation placeholders differ: {key}")
            translated = re.sub(r"\{(\d+)\}", lambda m: values[int(m[1])], translated)
        else:
            # Check unmatched SOURCE characters. Japanese translations naturally
            # contain Kanji, so target-script detection cannot detect omissions.
            pattern = re.compile("|".join(re.escape(source) for source, _ in self.fragments))
            replacements = dict(self.fragments)
            unresolved = pattern.sub("", original) if self.fragments else original
            if CJK.search(unresolved):
                self.missing.setdefault(key, {"source": original, "contexts": []})["contexts"].append(context)
                return text
            translated = pattern.sub(lambda match: replacements[match[0]], original) if self.fragments else original
        return prefix + translated + suffix


class Translator(HTMLParser):
    def __init__(self, source, catalog):
        super().__init__(convert_charrefs=False)
        self.source, self.catalog, self.stack, self.edits = source, catalog, [], []
        self.offsets = [0]
        self.offsets.extend(m.end() for m in re.finditer("\n", source))

    def position(self):
        line, column = self.getpos()
        return self.offsets[line - 1] + column

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        preserved = any(row[1] for row in self.stack) or bool(set(attrs.get("class", "").split()) & {"reference-citation", "citation"})
        if tag in {"script", "style", "code"}:
            preserved = True
        start, raw = self.position(), self.get_starttag_text()
        if not preserved:
            for match in re.finditer(r'([\w:-]+)\s*=\s*([\"\'])(.*?)\2', raw, re.S):
                name, value = match[1], html.unescape(match[3])
                if name in ATTRS and CJK.search(value):
                    translated = self.catalog.translate(value, f"html:{tag}@{name}")
                    self.edits.append((start + match.start(3), start + match.end(3), html.escape(translated, quote=True)))
        elif set(attrs.get("class", "").split()) & {"reference-citation", "citation"} and CJK.search(raw + self.source[start: self.source.find("</", start)]):
            if "lang" not in attrs:
                self.edits.append((start + len(raw) - 1, start + len(raw) - 1, ' lang="zh-CN"'))
        if tag not in VOID:
            self.stack.append((tag, preserved))

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in VOID:
            self.handle_endtag(tag)

    def handle_endtag(self, tag):
        for index in range(len(self.stack) - 1, -1, -1):
            if self.stack[index][0] == tag:
                del self.stack[index:]
                break

    def handle_data(self, data):
        if CJK.search(data) and not any(row[1] for row in self.stack):
            start = self.position()
            self.edits.append((start, start + len(data), html.escape(self.catalog.translate(html.unescape(data), "html:text"), quote=False)))

    def result(self):
        return apply_edits(self.source, self.edits)


def apply_edits(source, edits):
    for start, end, text in sorted(edits, reverse=True):
        source = source[:start] + text + source[end:]
    return source


def javascript(path, catalog):
    source = path.read_text("utf-8")
    result = subprocess.run(["node", str(ROOT / "scripts/website_js_strings.cjs"), str(path)],
                            capture_output=True, text=True, encoding="utf-8", check=True)
    edits = []
    for row in json.loads(result.stdout):
        text = row["text"]
        if text == "zh-CN":
            translated = catalog.data.get("formatLocale", catalog.language)
        elif CJK.search(text):
            translated = catalog.translate(text, path.name + ":" + row["kind"])
        else:
            continue
        if row["kind"] == "literal":
            value = json.dumps(translated, ensure_ascii=False)
        else:
            safe = translated.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
            value = ("`" if row["kind"] == "TemplateHead" else "}") + safe + ("`" if row["kind"] == "TemplateTail" else "${")
        edits.append((row["start"], row["end"], value))
    compiled = apply_edits(source, edits)
    subprocess.run(["node", "--check", "-"], input=compiled, text=True, encoding="utf-8", capture_output=True, check=True)
    return compiled


def language_controls(text, language):
    languages = available_languages()
    localized = language != "zh-CN"
    catalog = Catalog(language) if localized else None
    accessible = catalog.data.get("languageLabel", "Choose language") if catalog else "选择语言"
    globe = '<svg viewBox="0 0 24 24" aria-hidden="true"><circle cx="12" cy="12" r="9"/><path d="M3 12h18M12 3c5 5 5 13 0 18M12 3c-5 5-5 13 0 18"/></svg>'
    def target(row):
        if row["language"] == language:
            return "index.html"
        return ("../" if localized else "") + (row["directory"] + "/" if row["directory"] else "") + "index.html"
    links, alternate = [], []
    for row in languages:
        selected = row["language"] == language
        links.append(f'<a class="language-option" href="{target(row)}" lang="{row["language"]}" hreflang="{row["language"]}"'+(' aria-current="page"' if selected else '')+f'><span>{html.escape(row["nativeName"])}</span><span aria-hidden="true">'+('✓' if selected else '')+'</span></a>')
        alternate.append(f'<link rel="alternate" hreflang="{row["language"]}" href="{target(row)}">')
    control = f'<details class="language-picker"><summary class="language-switch" aria-label="{html.escape(accessible)}">{globe}<span lang="en">Language</span><span class="language-chevron" aria-hidden="true">⌄</span></summary><div class="language-options">'+''.join(links)+'</div></details>'
    github = re.search(r'<a class="header-github\b[\s\S]*?</a>', text)
    if not github:
        raise ValueError("Expected the website GitHub action")
    action = github[0]
    text = text[:github.start()] + text[github.end():]
    text, count = re.subn(r'(</nav>\s*</header>)', lambda m: m[0].replace('</nav>', '</nav><div class="header-actions">'+action+control+'</div>', 1), text, count=1)
    if count != 1:
        raise ValueError("Expected the website header")
    shared = "../" if localized else ""
    css_hash = hashlib.sha256((SITE / "site-languages.css").read_bytes()).hexdigest()[:12]
    js_hash = hashlib.sha256((SITE / "site-languages.js").read_bytes()).hexdigest()[:12]
    text = text.replace('</head>', f'<link rel="stylesheet" href="{shared}site-languages.css?v={css_hash}">\n<script src="{shared}site-languages.js?v={js_hash}" defer></script>\n' + '\n'.join(alternate) + '\n</head>')
    return text


def outputs(catalog):
    source = TEMPLATE.read_text("utf-8")
    downloads = json.loads((SITE / "assets/downloads.json").read_text("utf-8"))
    expected = [f'/releases/windows-x64/{downloads["version"]}/PhoneticToolbox-windows-x64.exe',
                f'/releases/windows-x64/{downloads["version"]}/PhoneticToolbox-{downloads["version"]}-windows-x64-setup.exe']
    expected.append(downloads["macos"]["url"])
    if any(f'href="{url}"' not in source for url in expected):
        raise ValueError("Homepage download links differ from assets/downloads.json; reconcile the maintained template before building")
    chinese = language_controls(source, "zh-CN")
    parser = Translator(source, catalog)
    parser.feed(source)
    english = parser.result().replace('<html lang="zh-CN">', f'<html lang="{catalog.language}">', 1)
    hero = catalog.data["hero"]
    heading = f'<h1 id="hero-heading" class="localized-heading {catalog.language}-heading">{html.escape(hero["lines"][0])}<br><em>{html.escape(hero["lines"][1])}</em></h1><p class="language-note">{html.escape(hero["note"])}</p>'
    english = re.sub(r'<h1 id="hero-heading"[\s\S]*?</h1>', heading, english, count=1)
    # Share media and CSS. Interactive English strings are compiled separately.
    english = re.sub(r'((?:src|href|poster)=")((?:assets/|site\.css|ime-downloads\.css)[^\"]*)', r'\1../\2', english)
    english = language_controls(english, catalog.language)
    result = {SITE / "index.html": chinese, SITE / catalog.language / "index.html": english}
    for file in ("site.js", "ime-downloads.js"):
        result[SITE / catalog.language / file] = javascript(SITE / file, catalog)
    return result


def build(check=False, inventory=False, language=None):
    catalogs = [Catalog(row["language"]) for row in available_languages()[1:] if language is None or row["language"] == language]
    result = {}
    for catalog in catalogs:
        result.update(outputs(catalog))
    if inventory:
        print(json.dumps(catalogs[0].missing if language else {c.language: c.missing for c in catalogs}, ensure_ascii=False, indent=2))
        return
    missing = {c.language: c.missing for c in catalogs if c.missing}
    if missing:
        print(json.dumps(missing, ensure_ascii=False, indent=2))
        raise SystemExit("Untranslated messages; update the corresponding temporary-site/locales catalog")
    changed = []
    for path, text in result.items():
        if not path.exists() or path.read_text("utf-8") != text:
            changed.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    print(json.dumps(dict(complete=True, messages={c.language: len(c.used) for c in catalogs}, changed=changed, check=check), ensure_ascii=False))
    if check and changed:
        raise SystemExit("Generated website files need rebuilding")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--inventory", action="store_true")
    parser.add_argument("--language", choices=[row["language"] for row in available_languages()[1:]])
    args = parser.parse_args()
    if args.language and not args.inventory:
        parser.error("--language only selects an --inventory report; builds always update all languages")
    build(args.check, args.inventory, args.language)
