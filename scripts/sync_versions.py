"""Synchronize application versions; root legacy pyproject remains untouched."""
import argparse
import json
import re
import subprocess
import sys
import importlib.metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    version = json.loads((ROOT / 'release/version.json').read_text('utf-8'))
    outputs = {}
    for package in ['packages/phonetic_core', 'backend', 'desktop']:
        path = ROOT / package / 'pyproject.toml'
        content = path.read_text('utf-8')
        core_version=version.get('core_version',version['app_version'])
        package_version=core_version if package=='packages/phonetic_core' else version['app_version']
        content = re.sub(r'(?m)^version = ".*"$', f'version = "{package_version}"', content)
        content = re.sub(r'(phonetic-core(?:\[[^\]]+\])?==)[^"\s]+', lambda m: m[1] + core_version, content)
        outputs[path] = content
    frontend = ROOT / 'frontend/package.json'
    value = json.loads(frontend.read_text('utf-8'))
    value['version'] = version['frontend_version']
    # Formatting is preserved if only semantic version data is already correct.
    if json.loads(frontend.read_text('utf-8')) != value:
        outputs[frontend] = json.dumps(value, indent=2) + '\n'
    lock = ROOT / 'frontend/package-lock.json'
    if lock.exists():
        data = json.loads(lock.read_text('utf-8'))
        data['version'] = version['frontend_version']
        data['packages']['']['version'] = version['frontend_version']
        if json.loads(lock.read_text('utf-8')) != data:
            outputs[lock] = json.dumps(data, indent=2) + '\n'
    outputs[ROOT / 'frontend/src/version.json'] = json.dumps(version, indent=2) + '\n'
    outputs[ROOT / 'backend/src/ptb_api/protocol_version.py'] = (
        '# Generated by scripts/sync_versions.py; do not edit.\n' + f'API_VERSION = {version["api_version"]!r}\nCORE_VERSION = {core_version!r}\n')
    drift = []
    for path, content in outputs.items():
        if not path.exists() or path.read_text('utf-8') != content:
            if args.check:
                drift.append(path.relative_to(ROOT).as_posix())
            else:
                path.write_text(content, encoding='utf-8', newline='\n')
    # Editable metadata is also frozen into the EXE and scientific workers.
    # Regenerate it through setuptools rather than carrying stale egg-info.
    for package, name in [('packages/phonetic_core', 'phonetic-core'), ('backend', 'ptb-api'), ('desktop', 'ptb-desktop')]:
        expected = core_version if name == 'phonetic-core' else version['app_version']
        if not args.check:
            subprocess.run([sys.executable, '-B', '-c', 'from setuptools import setup; setup(script_args=["egg_info"])'],
                           cwd=ROOT / package, check=True, stdout=subprocess.DEVNULL)
        matches = [d for d in importlib.metadata.distributions(path=[str(ROOT / package / 'src')])
                   if d.metadata['Name'].lower().replace('_', '-') == name]
        if len(matches) != 1 or matches[0].version != expected:
            drift.append(package + '/src (regenerate package metadata)')
    print(json.dumps({'version_drift': drift}))
    raise SystemExit(bool(drift))


if __name__ == '__main__':
    main()
