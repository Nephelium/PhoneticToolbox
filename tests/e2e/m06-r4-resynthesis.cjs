const fs=require('node:fs/promises'),path=require('node:path'),assert=require('node:assert/strict');
module.exports=async function({page,scope,click,idle,out,checks}){
 await page.setViewportSize({width:1920,height:1000});
 await scope.getByLabel('合成方法',{exact:true}).selectOption('world');
 assert.equal(await scope.getByLabel('发声类型预设').count(),0);
 assert.equal(await scope.getByLabel('IPA 元音序列').count(),0);
 assert(await scope.getByLabel('曲线覆盖',{exact:true}).isDisabled());
 await click('打开音频目录');
 const picker=scope.getByLabel('源音频',{exact:true});await picker.locator('option').nth(1).waitFor({state:'attached'});
 await picker.selectOption({index:1});
 await page.waitForTimeout(150);
 if(await page.getByRole('dialog').count())await click('应用并覆盖');
 await idle();
 await scope.getByLabel('F0 提取算法').selectOption('harvest');await click('提取参数');await idle();
 assert((await scope.innerText()).includes('F0 提取完成'));
 await click('重合成音频');await idle();assert((await scope.innerText()).includes('合成完成'));
 await click('播放选区');await click('停止');
 let download=page.waitForEvent('download');await click('导出分析数据');await (await download).saveAs(path.join(out,'r4-world-analysis.npz'));
 download=page.waitForEvent('download');await click('导出参数');await (await download).saveAs(path.join(out,'r4-world-original.csv'));
 const text=await fs.readFile(path.join(out,'r4-world-original.csv'),'utf8');assert(text.includes('world')&&text.includes('source_sha256'));
 await scope.getByLabel('重合成音高').selectOption('curve');await scope.getByLabel('曲线覆盖',{exact:true}).fill('220');await click('应用覆盖');
 await scope.getByLabel('谱包络频率比例').fill('1.1');await scope.getByLabel('非周期幅度比例').fill('0.8');
 await scope.getByLabel('总时长',{exact:true}).fill('0.9');await click('应用时长');
 await click('重合成音频');await idle();assert((await scope.innerText()).includes('合成完成'));
 await click('导出音频');await scope.getByText('已导出合成结果',{exact:true}).waitFor();
 download=page.waitForEvent('download');await click('导出分析数据');await (await download).saveAs(path.join(out,'r4-world-edited.npz'));
 checks.push('R4 WORLD: real Harvest extraction, original and edited F0/duration/envelope/AP, playback, numeric NPZ and native full result save');
 await scope.getByLabel('合成方法',{exact:true}).selectOption('psola');
 assert.equal(await scope.getByLabel('谱包络频率比例').count(),0);
 await scope.getByLabel('F0 提取算法').selectOption('praat_cc');
 await click('重合成音频');await idle();assert((await scope.innerText()).includes('合成完成'));
 download=page.waitForEvent('download');await click('导出分析数据');await (await download).saveAs(path.join(out,'r4-psola-analysis.npz'));
 checks.push('R4 PSOLA: real reconstruction after method switch, separate supported controls, edited pitch and time');
 const layouts=[];
 for(const method of ['world','psola'])for(const [width,height] of [[1920,1000],[1440,900],[900,700]])for(const theme of ['light','dark']){
  await page.setViewportSize({width,height});await click('设置');await click(theme==='light'?'浅色':'深色');await page.locator('nav').getByRole('button',{name:'语音合成',exact:true}).click();
  await scope.getByLabel('合成方法',{exact:true}).selectOption(method);await page.waitForTimeout(350);
  const m=await scope.evaluate(r=>{const b=e=>{const p=e.getBoundingClientRect();return {x:p.x,y:p.y,w:p.width,h:p.height,b:p.bottom}};return {bar:b(r.querySelector('.m06-transport')),root:b(r),work:b(r.querySelector('.module-workbench')),left:b(r.querySelector('.workbench-left')),center:b(r.querySelector('.workbench-center')),right:b(r.querySelector('.workbench-right')),overflow:r.scrollWidth-r.clientWidth,players:r.querySelectorAll('.transport-controls').length};});
  assert(m.overflow<=1&&m.players===1);assert(m.bar.b<=m.root.b+1&&m.bar.y>=m.work.b-1);
  if(m.work.w<=1060)assert(m.right.y>=Math.max(m.left.b,m.center.b)-1);
  const background=await page.evaluate(()=>getComputedStyle(document.documentElement).getPropertyValue('--app').trim());
  if(theme==='dark')assert.notEqual(background,layouts.at(-1).background);
  layouts.push({method,width,height,theme,background,...m});
  if(width!==1440)await page.screenshot({path:path.join(out,`r4-${method}-${width}-${theme}.png`),fullPage:true});
 }
 await fs.writeFile(path.join(out,'r4-layouts.json'),JSON.stringify(layouts,null,2));
 checks.push('R4 layouts: WORLD and PSOLA × 3 sizes × light/dark; full-width footer and nonoverlapping narrow content');
 await page.setViewportSize({width:1920,height:1000});await scope.getByLabel('合成方法',{exact:true}).selectOption('world');
 await click('保存参数草稿');await page.getByLabel('关闭 语音合成',{exact:true}).click();
 await page.locator('nav').getByRole('button',{name:'语音合成',exact:true}).click();await scope.waitFor();
 assert.equal(await scope.getByLabel('合成方法').inputValue(),'world');
 assert(await scope.getByRole('button',{name:'重合成音频',exact:true}).isDisabled());
 await click('打开音频目录');await scope.getByLabel('源音频',{exact:true}).selectOption({index:1});
 await scope.getByText('原录音已关联，保留导入的参数与 F0 编辑。',{exact:true}).waitFor();
 assert.equal(await scope.getByLabel('曲线覆盖',{exact:true}).inputValue(),'220');
 await click('重合成音频');await idle();assert((await scope.innerText()).includes('合成完成'));
 checks.push('R4 reload: saved source hash, method, ratios and F0 retained; re-link matching source without overwriting edited curves');
};
